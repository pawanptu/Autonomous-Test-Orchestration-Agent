"""Generator sub-agent: plan steps in, executable Playwright tests out.

The hard part of test generation is not writing Python - it is not writing
Python that references elements which do not exist. So generation happens in
three passes:

1. **Live walk.** The flow is walked in a real browser. Before each step, the
   step's plain-language target is resolved against the *current* DOM by
   :mod:`browser.selectors`, and non-assertion steps are then performed so the
   next step is resolved against the page state it will actually meet. Nothing
   reaches the code writer that has not been proved to exist.

2. **Model authoring.** The small, fast model writes the test body from the
   flow plus the resolved locators. Judgment already happened upstream; this is
   mechanical translation, so it must never burn the 70B.

3. **Gate and fall back.** The output is AST-audited
   (:mod:`browser.sandbox`), scanned for credential literals, and checked for
   assertions. Invalid output earns exactly one repair round-trip. If it still
   fails, a deterministic compiler renders the *same validated steps and
   locators* into source, and the report records ``generated_by_model`` as the
   fallback compiler so nobody mistakes it for model output.

The fallback is a compiler over agent-produced artifacts, not a hand-written
test: its input is the agent's plan and the agent's live-resolved selectors,
and no human ever edits its output.

Trade-off, stated plainly: the live walk *interacts* with the target - it
clicks and fills. Point this agent at a staging or demo environment, not at
production data you care about.
"""

