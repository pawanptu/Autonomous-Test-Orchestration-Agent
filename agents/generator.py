@pytest_asyncio.fixture
async def page():
    """A fresh browser, context and page per test.

    Function-scoped on purpose. A session-scoped browser would be faster, but
    a session-scoped async fixture has to share an event loop with the tests,
    and getting that wrong under pytest-asyncio hangs the whole suite with no
    output. Each test paying ~1s of launch cost is a good trade for a harness
    that always runs. It also guarantees flow isolation: no test can inherit
    cookies or local storage from the one before it.
    """
    async with async_playwright() as playwright:
        browser = await playwright.chromium.launch(headless=HEADLESS)
        options = {"viewport": {"width": 1280, "height": 900}, "ignore_https_errors": True}
        if STORAGE_STATE and os.path.exists(STORAGE_STATE):
            options["storage_state"] = STORAGE_STATE
        context = await browser.new_context(**options)
        context.set_default_timeout(8000)
        page = await context.new_page()
        try:
            yield page
        finally:
            await context.close()
            await browser.close()


